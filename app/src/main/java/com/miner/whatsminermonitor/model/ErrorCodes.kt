    fun describe(code: Int): WhatsminerErrorDetail {
        val known = catalog[code]
        return if (known != null) {
            WhatsminerErrorDetail(code, known.first, known.second)
        } else {
            WhatsminerErrorDetail(code, fallbackTitle(code), fallbackSolution(code))
        }
    }

    private fun fallbackTitle(code: Int): String = when (code) {
        in 100..199 -> "خطای فن (کد $code)"
        in 200..299 -> "خطای منبع تغذیه / پاور (کد $code)"
        in 300..399 -> "خطای سنسور دمای هش‌برد (کد $code)"
        in 400..499 -> "خطای حافظه یا تنظیمات هش‌برد (کد $code)"
        in 500..599 -> "خطای اتصال یا چیپ هش‌برد (کد $code)"
        in 600..699 -> "خطای دمای محیط (کد $code)"
        in 700..799 -> "خطای برد کنترل (کد $code)"
        in 800..899 -> "خطای فریمور (کد $code)"
        in 2000..2999 -> "خطای شبکه یا استخر ماینینگ (کد $code)"
        in 5000..5999 -> "خطای فرکانس هش‌برد (کد $code)"
        in 8000..8999 -> "ناسازگاری نسخهٔ فریمور (کد $code)"
        else -> "کد خطای ناشناخته ($code)"
    }

    private fun fallbackSolution(code: Int): String = when (code) {
        in 100..199 -> "اتصال و سلامت فن‌ها را بررسی کنید؛ در صورت نیاز فن یا پاور را تعویض کنید"
        in 200..299 -> "شرایط برق ورودی (ولتاژ/جریان) و اتصال پاور را بررسی کنید؛ در صورت تکرار پاور را تعویض کنید"
        in 300..399 -> "اتصال هش‌برد و پیچ‌های برد کنترل را بررسی کنید"
        in 400..499 -> "اتصال برد رابط را بررسی کنید؛ در صورت ادامه با تکنسین تماس بگیرید"
        in 500..599 -> "اتصال هش‌برد، برد رابط و کانکتورها را بررسی و در صورت نیاز تمیز کنید"
        in 600..699 -> "دمای محیط اتاق ماینینگ را کاهش دهید و تهویه را بهبود ببخشید"
        in 700..799 -> "فریمور را به آخرین نسخه به‌روزرسانی کرده و پیچ‌های برد کنترل را بررسی کنید"
        in 800..899 -> "فریمور دستگاه را دوباره نصب یا به‌روزرسانی کنید"
        in 2000..2999 -> "اتصال شبکه و تنظیمات استخر (Pool) را بررسی کنید"
        in 5000..5999 -> "دستگاه را ری‌استارت کنید؛ در صورت تکرار با پشتیبانی تماس بگیرید"
        in 8000..8999 -> "نسخهٔ صحیح فریمور متناسب با مدل دستگاه را نصب کنید"
        else -> "برای بررسی دقیق‌تر با پشتیبانی یا تکنسین تماس بگیرید"
    }
